/** Fixed calendar wheel, independent of render count, weather refresh and personal preferences. */
export function tipPhrase<K extends keyof typeof tipPhrases>(kind: K, day: string, offset = 0): string {
  const options = tipPhrases[kind];
  const ordinal = Math.floor(Date.parse(`${day}T00:00:00Z`) / 86400000);
  const index = ((ordinal + offset) % options.length + options.length) % options.length;
  return options[index];
}
